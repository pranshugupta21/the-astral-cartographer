import { GoogleGenAI, ThinkingLevel } from '@google/genai';
import { AnalysisResult, IndexedFile } from './types';

let genAIClient: GoogleGenAI | null = null;

function getClient(): GoogleGenAI | null {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) return null;
  if (!genAIClient) {
    genAIClient = new GoogleGenAI({
      apiKey,
      httpOptions: {
        headers: {
          'User-Agent': 'aistudio-build',
        },
      },
    });
  }
  return genAIClient;
}

export async function askCodebaseQuestion(
  question: string,
  analysis: AnalysisResult,
  selectedFileId?: string,
  allFiles?: Record<string, IndexedFile>
): Promise<{ answer: string; evidence: string[]; isAiPowered: boolean }> {
  const ai = getClient();

  // If Gemini is not configured, generate a deterministic graph-grounded response
  if (!ai) {
    return generateDeterministicAnswer(question, analysis, selectedFileId);
  }

  try {
    // 1. Build bounded context
    const graphSummary = {
      repository: analysis.repo.fullName,
      totalFiles: analysis.metrics.totalFiles,
      resolvedEdges: analysis.metrics.resolvedEdgesCount,
      cycles: analysis.cycles.map((c) => c.files.join(' -> ')),
      topHubs: analysis.nodes
        .filter((n) => n.fanIn >= 3 || n.fanOut >= 4)
        .slice(0, 8)
        .map((n) => ({
          path: n.path,
          fanIn: n.fanIn,
          fanOut: n.fanOut,
          complexity: n.complexity,
        })),
      onboardingTop3: analysis.onboardingPath.slice(0, 3).map((s) => ({
        rank: s.rank,
        file: s.filePath,
        reason: s.reason,
      })),
    };

    // Include selected file excerpt if available
    let sourceSnippet = '';
    if (selectedFileId && allFiles && allFiles[selectedFileId]?.content) {
      const full = allFiles[selectedFileId].content!;
      // Limit to first 120 lines
      const lines = full.split('\n').slice(0, 120).join('\n');
      sourceSnippet = `\nSELECTED FILE (${selectedFileId}):\n\`\`\`\n${lines}\n\`\`\``;
    }

    const systemPrompt = `You are the Astral Cartographer, an expert software architecture intelligence assistant.
You explain codebases strictly grounded in architectural evidence from the AST dependency graph and indexed files.
Rules:
1. Ground answers in the provided graph evidence, file paths, and dependency relationships.
2. Explicitly cite specific file paths (e.g. \`src/api.ts\`).
3. Distinguish proven architectural facts (e.g. "File A imports File B") from inferences.
4. If the provided evidence is insufficient to verify an implementation detail, clearly state that.
5. Format your response cleanly with clear headings and concise bullet points.`;

    const userPrompt = `REPOSITORY ARCHITECTURAL CONTEXT:
${JSON.stringify(graphSummary, null, 2)}
${sourceSnippet}

USER QUESTION:
"${question}"

Provide a concise, grounded architectural answer with specific file paths.`;

    const generatePromise = ai.models.generateContent({
      model: 'gemini-3.8-flash',
      contents: userPrompt,
      config: {
        systemInstruction: systemPrompt,
        temperature: 0.2,
        thinkingConfig: { thinkingLevel: ThinkingLevel.LOW },
      },
    });

    const timeoutPromise = new Promise<never>((_, reject) =>
      setTimeout(() => reject(new Error('Gemini API call timed out after 30s')), 30000)
    );

    const response = await Promise.race([generatePromise, timeoutPromise]);

    const answer = response.text || 'No response generated by assistant.';
    const citedFiles: string[] = [];
    for (const node of analysis.nodes) {
      if (answer.includes(node.path) || answer.includes(node.name)) {
        citedFiles.push(node.path);
      }
    }

    return {
      answer,
      evidence: Array.from(new Set(citedFiles)).slice(0, 6),
      isAiPowered: true,
    };
  } catch (err: any) {
    console.warn('Gemini live call unavailable, using architectural index:', err.message || String(err));
    return generateDeterministicAnswer(question, analysis, selectedFileId);
  }
}

function generateDeterministicAnswer(
  question: string,
  analysis: AnalysisResult,
  selectedFileId?: string
): { answer: string; evidence: string[]; isAiPowered: boolean } {
  const q = question.toLowerCase();
  const evidence: string[] = [];

  // Question: Execution entry point
  if (q.includes('start') || q.includes('begin') || q.includes('entry') || q.includes('execution')) {
    const entry = analysis.onboardingPath.find((s) => s.rank === 1 || s.rank === 2);
    if (entry) {
      evidence.push(entry.filePath);
      return {
        answer: `### Primary Execution Entry Point\n\nApplication bootstrap is located at **\`${entry.filePath}\`** (${entry.role}).\n\n**Architectural Evidence:**\n- ${entry.reason}\n- **Direct Dependencies (${entry.dependencies.length}):** ${entry.dependencies.slice(0, 4).map((d) => `\`${d}\``).join(', ') || 'None'}\n- **Direct Dependents (${entry.dependents.length}):** ${entry.dependents.slice(0, 4).map((d) => `\`${d}\``).join(', ') || 'None'}`,
        evidence,
        isAiPowered: false,
      };
    }
  }

  // Question: Circular dependencies
  if (q.includes('cycle') || q.includes('circular') || q.includes('loop')) {
    if (analysis.cycles.length > 0) {
      const topCycle = analysis.cycles[0];
      topCycle.files.forEach((f) => evidence.push(f));
      return {
        answer: `### Circular Dependency Analysis\n\nThe AST analyzer detected **${analysis.cycles.length}** circular dependency loop(s).\n\n**Primary Cycle Detected:**\n${topCycle.files.map((f, i) => `${i + 1}. \`${f}\``).join(' ➔ ')}\n\n**Architectural Impact:**\nCircular imports force module bundlers to generate dynamic lookup closures and can cause runtime \`undefined\` imports during circular instantiation.`,
        evidence,
        isAiPowered: false,
      };
    } else {
      return {
        answer: `### Circular Dependency Analysis\n\n**No circular dependencies detected!** The local module graph is a Directed Acyclic Graph (DAG) across all ${analysis.metrics.resolvedEdgesCount} resolved edges.`,
        evidence: [],
        isAiPowered: false,
      };
    }
  }

  // Question: Selected file or what does this depend on
  if (selectedFileId && (q.includes('depend') || q.includes('import') || q.includes('selected') || q.includes('this') || q.includes('risk'))) {
    const node = analysis.nodes.find((n) => n.id === selectedFileId);
    const deps = analysis.edges.filter((e) => e.source === selectedFileId).map((e) => e.target);
    const dependents = analysis.edges.filter((e) => e.target === selectedFileId).map((e) => e.source);

    if (node) {
      evidence.push(node.path);
      deps.slice(0, 3).forEach((d) => evidence.push(d));
      return {
        answer: `### Architectural Inspection of \`${node.path}\`\n\n- **Module Role:** \`${node.fileRole}\` (${node.language})\n- **Size & Complexity:** ${node.lineCount} lines, cyclomatic complexity: ${node.complexity}\n- **Outgoing Dependencies (Fan-Out: ${node.fanOut}):**\n${deps.length > 0 ? deps.map((d) => `  - \`${d}\``).join('\n') : '  *(No outgoing local dependencies)*'}\n- **Incoming Consumers (Fan-In: ${node.fanIn}):**\n${dependents.length > 0 ? dependents.map((d) => `  - \`${d}\``).join('\n') : '  *(No other local files import this)*'}\n\n**Modification Risk:** ${node.fanIn >= 3 ? '⚠️ **High Blast Radius** — modifying this module will impact ' + node.fanIn + ' dependent modules.' : '✅ **Isolated / Low Blast Radius** — limited direct dependents.'}`,
        evidence,
        isAiPowered: false,
      };
    }
  }

  // Default architectural summary
  const topHub = analysis.nodes.slice().sort((a, b) => b.fanIn - a.fanIn)[0];
  if (topHub) evidence.push(topHub.path);

  return {
    answer: `### Codebase Architecture Overview\n\n- **Repository:** \`${analysis.repo.fullName}\`\n- **Analyzed Source Modules:** ${analysis.metrics.analyzedFiles} files (${analysis.metrics.totalLines} lines of code)\n- **Dependency Mesh:** ${analysis.metrics.resolvedEdgesCount} resolved local imports, ${analysis.metrics.externalImportsCount} external package imports.\n- **Primary Architectural Hub:** \`${topHub ? topHub.path : 'None'}\` (imported by ${topHub ? topHub.fanIn : 0} modules)\n- **Detected Circular Dependencies:** ${analysis.cycles.length}\n\n*Tip: Select any node in the interactive atlas or type a specific file path to inspect its blast radius and upstream dependencies.*`,
    evidence,
    isAiPowered: false,
  };
}
