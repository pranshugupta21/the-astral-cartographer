import React, { useState } from 'react';
import { Download, Copy, Check, X, FileJson, FileText } from 'lucide-react';
import { AnalysisResult } from '../types';

interface ExportModalProps {
  analysis: AnalysisResult;
  onClose: () => void;
}

export function ExportModal({ analysis, onClose }: ExportModalProps) {
  const [activeFormat, setActiveFormat] = useState<'json' | 'markdown'>('json');
  const [copied, setCopied] = useState(false);

  // Generate JSON payload
  const jsonExport = JSON.stringify(
    {
      repository: analysis.repo,
      metrics: analysis.metrics,
      nodesCount: analysis.nodes.length,
      edgesCount: analysis.edges.length,
      nodes: analysis.nodes,
      edges: analysis.edges,
      cycles: analysis.cycles,
      findings: analysis.findings,
      onboardingPath: analysis.onboardingPath,
    },
    null,
    2
  );

  // Generate Markdown report
  const markdownExport = `# Architectural Intelligence Report: ${analysis.repo.fullName}
Generated by The Astral Cartographer on ${new Date(analysis.createdAt).toLocaleDateString()}

## 1. Executive Metrics
- **Total Indexed Files:** ${analysis.metrics.analyzedFiles}
- **Lines of Code:** ${analysis.metrics.totalLines}
- **Resolved Dependency Edges:** ${analysis.metrics.resolvedEdgesCount}
- **External Dependencies:** ${analysis.metrics.externalImportsCount}
- **Circular Dependency Loops:** ${analysis.cycles.length}
- **Primary Coupling Hub:** ${analysis.metrics.maxFanIn.file} (imported by ${analysis.metrics.maxFanIn.count} modules)
- **Primary Orchestrator:** ${analysis.metrics.maxFanOut.file} (imports ${analysis.metrics.maxFanOut.count} modules)

## 2. Circular Dependencies
${
  analysis.cycles.length === 0
    ? '✅ No circular dependency loops detected.'
    : analysis.cycles
        .map((c, i) => `### Cycle #${i + 1} (${c.length} files, ${c.severity})\n${c.files.join(' ➔ ')}`)
        .join('\n\n')
}

## 3. Key Architectural Findings
${analysis.findings
  .map(
    (f) => `### [${f.severity.toUpperCase()}] ${f.title}
- **Category:** ${f.category}
- **Impact:** ${f.impact}
- **Recommendation:** ${f.recommendation}
- **Affected Files:** ${f.affectedFiles.join(', ')}`
  )
  .join('\n\n')}

## 4. Recommended Onboarding Path
${analysis.onboardingPath
  .map(
    (step) => `${step.rank}. **\`${step.filePath}\`** (${step.role})
   - *Reason:* ${step.reason}
   - *Key Symbols:* ${step.keySymbols.join(', ') || 'N/A'}`
  )
  .join('\n\n')}
`;

  const currentContent = activeFormat === 'json' ? jsonExport : markdownExport;

  const handleCopy = () => {
    navigator.clipboard.writeText(currentContent);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const filename = `${analysis.repo.repo}_architecture_${Date.now()}.${
      activeFormat === 'json' ? 'json' : 'md'
    }`;
    const blob = new Blob([currentContent], {
      type: activeFormat === 'json' ? 'application/json' : 'text/markdown',
    });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="fixed inset-0 bg-black/75 backdrop-blur-sm flex items-center justify-center p-4 z-50">
      <div className="w-full max-w-2xl bg-[#12141a] border border-[#2a303e] rounded shadow-2xl flex flex-col max-h-[85vh] overflow-hidden">
        {/* Header */}
        <div className="p-4 border-b border-[#202533] flex items-center justify-between">
          <div className="flex items-center gap-2">
            <Download className="w-4 h-4 text-[#c5a059]" />
            <span className="font-serif-atlas text-sm font-semibold text-[#f4efe6]">
              Export Architectural Intelligence
            </span>
          </div>
          <button
            onClick={onClose}
            className="text-[#6c7485] hover:text-[#ded9cd] p-1 rounded transition-colors"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        {/* Format Selector */}
        <div className="px-4 py-2 bg-[#0d0f14] border-b border-[#202533] flex items-center justify-between text-xs">
          <div className="flex items-center gap-2">
            <button
              onClick={() => setActiveFormat('json')}
              className={`px-3 py-1 rounded flex items-center gap-1.5 font-mono ${
                activeFormat === 'json'
                  ? 'bg-[#c5a059] text-black font-semibold'
                  : 'text-[#8e95a5] hover:text-[#ded9cd]'
              }`}
            >
              <FileJson className="w-3.5 h-3.5" />
              <span>Graph JSON</span>
            </button>
            <button
              onClick={() => setActiveFormat('markdown')}
              className={`px-3 py-1 rounded flex items-center gap-1.5 font-mono ${
                activeFormat === 'markdown'
                  ? 'bg-[#c5a059] text-black font-semibold'
                  : 'text-[#8e95a5] hover:text-[#ded9cd]'
              }`}
            >
              <FileText className="w-3.5 h-3.5" />
              <span>Report Markdown</span>
            </button>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={handleCopy}
              className="px-2.5 py-1 bg-[#1a1e29] hover:bg-[#242b3b] border border-[#2a303e] text-[#c9c3b6] rounded flex items-center gap-1 transition-colors text-xs"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copied ? 'Copied' : 'Copy'}</span>
            </button>
            <button
              onClick={handleDownload}
              className="px-2.5 py-1 bg-[#8b263e] hover:bg-[#a12f4b] text-white rounded flex items-center gap-1 transition-colors text-xs font-medium"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download</span>
            </button>
          </div>
        </div>

        {/* Content Preview */}
        <div className="p-4 flex-1 overflow-y-auto bg-[#0a0b0e]">
          <pre className="font-mono text-[11px] text-[#ded9cd] leading-relaxed whitespace-pre-wrap select-all">
            {currentContent}
          </pre>
        </div>
      </div>
    </div>
  );
}
